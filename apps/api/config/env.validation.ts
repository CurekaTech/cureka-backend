import * as Joi from 'joi';

export const envValidationSchema = Joi.object({
  NODE_ENV: Joi.string().valid('development', 'production', 'test', 'staging').default('development'),
  PORT: Joi.number().default(3000),
  DATABASE_URL: Joi.string().uri().required(),
  REDIS_HOST: Joi.string().default('localhost'),
  REDIS_PORT: Joi.number().default(6379),
  REDIS_PASSWORD: Joi.string().allow('').optional(),
  REDIS_USERNAME: Joi.string().allow('').optional(),
  REDIS_TLS: Joi.string().valid('true', 'false').default('false'),
  CACHE_TTL: Joi.number().default(300),
  ATTRIBUTE_CACHE_TTL: Joi.number().default(300),
  BRAND_CACHE_TTL: Joi.number().default(300),
  CATEGORY_CACHE_TTL: Joi.number().default(600),
  PRODUCT_CACHE_TTL: Joi.number().default(900),
  HOMEPAGE_CACHE_TTL: Joi.number().default(600),
  SESSION_CACHE_TTL: Joi.number().default(300),
  OTP_RESEND_COOLDOWN_SECONDS: Joi.number().integer().min(30).max(300).default(60),
  REDIS_CONNECT_TIMEOUT_MS: Joi.number().integer().min(500).default(5000),
  REDIS_OPERATION_TIMEOUT_MS: Joi.number().integer().min(500).default(8000),
  JWT_SECRET: Joi.string().min(32).required(),
  JWT_EXPIRES_IN: Joi.string().default('7d'),
  JWT_ACCESS_EXPIRES_IN: Joi.string().default('15m'),
  JWT_REFRESH_EXPIRES_IN_DAYS: Joi.number().integer().min(1).max(365).default(90),
  LOG_LEVEL: Joi.string().valid('fatal', 'error', 'warn', 'info', 'debug', 'trace').default('info'),
  CORS_ORIGINS: Joi.string().optional(),
  COOKIE_SECURE: Joi.string().valid('true', 'false').optional(),
  DATABASE_LOGGING: Joi.string().valid('true', 'false').optional(),
  STORAGE_DRIVER: Joi.string().valid('local', 'gcs').default('local'),
  UPLOAD_DIR: Joi.string().optional(),
  UPLOAD_MAX_IMAGE_FILE_SIZE: Joi.number().default(1048576),
  UPLOAD_MAX_VIDEO_FILE_SIZE: Joi.number().default(20971520),
  UPLOAD_MAX_MULTIPART_FILES: Joi.number().integer().min(1).max(200).default(50),
  UPLOAD_ALLOWED_MIME_TYPES: Joi.string().optional(),
  GCS_BUCKET_NAME: Joi.string().when('STORAGE_DRIVER', {
    is: 'gcs',
    then: Joi.required(),
    otherwise: Joi.optional(),
  }),
  GCS_CREDENTIALS_PATH: Joi.string().when('STORAGE_DRIVER', {
    is: 'gcs',
    then: Joi.required(),
    otherwise: Joi.optional(),
  }),
  GCS_SIGNED_URL_TTL_SECONDS: Joi.number().integer().min(60).max(604800).default(3600),
  // Unicommerce integration credentials — issued by Cureka to Unicommerce per seller
  UNICOMMERCE_USERNAME: Joi.string().optional(),
  UNICOMMERCE_PASSWORD: Joi.string().optional(),
  UNICOMMERCE_DEFAULT_FACILITY_CODE: Joi.string().optional(),
  UNICOMMERCE_DEFAULT_HSN_CODE: Joi.string().optional(),
  UNICOMMERCE_PRODUCT_BASE_URL: Joi.string().uri().optional(),
  RAZORPAY_KEY_ID: Joi.string().optional(),
  RAZORPAY_SECRET: Joi.string().optional(),
  RAZORPAY_WEBHOOK_SECRET: Joi.string().optional(),
  RAZORPAY_PAYMENT_LINK_EXPIRY_MINUTES: Joi.number().integer().min(1).max(525600).default(4320),
  RAZORPAY_CALLBACK_URL: Joi.string().uri().optional(),
  RAZORPAY_WEBHOOK_URL: Joi.string().uri().optional(),

  SHIPPING_FREE_THRESHOLD: Joi.number().min(0).default(900),
  SHIPPING_FLAT_FEE: Joi.number().min(0).default(50),
  SHIPWAY_EMAIL: Joi.string().allow('').optional(),
  SHIPWAY_LICENSE_KEY: Joi.string().allow('').optional(),
  SHIPWAY_BASE_URL: Joi.string().uri().default('https://app.shipway.com'),
  SHIPWAY_WAREHOUSE_ID: Joi.string().allow('').optional(),
  SHIPWAY_RETURN_WAREHOUSE_ID: Joi.string().allow('').optional(),
  SHIPWAY_CARRIER_ID: Joi.number().integer().positive().optional(),
  SHIPWAY_WEBHOOK_SECRET: Joi.string().allow('').optional(),
  SHIPWAY_TIMEOUT_MS: Joi.number().integer().min(1000).max(60000).default(15000),
  /** Public storefront origin used for Razorpay payment-link redirect after checkout. */
  STOREFRONT_URL: Joi.string().uri().optional(),

  CASHFREE_APP_ID: Joi.string().optional(),
  CASHFREE_SECRET_KEY: Joi.string().optional(),
  CASHFREE_ENV: Joi.string().valid('sandbox', 'production', 'SANDBOX', 'PRODUCTION').default('sandbox'),
  CASHFREE_API_VERSION: Joi.string().default('2023-08-01'),
  CASHFREE_WEBHOOK_SECRET: Joi.string().optional(),

  TYPESENSE_HOST: Joi.string().optional(),
  TYPESENSE_API_KEY: Joi.string().optional(),
  TYPESENSE_SEARCH_API_KEY: Joi.string().optional(),
  TYPESENSE_COLLECTION: Joi.string().default('products'),
});
